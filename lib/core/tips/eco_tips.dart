/// Ротация советов дня (клиентский каталог для 1.0).
abstract final class EcoTips {
  static const items = <String>[
    'Споласкивайте бутылки перед сдачей — волонтёрам проще проверить заявку.',
    'Сжимайте пластик: в контейнер помещается больше, а вы быстрее набираете кг.',
    'Батарейки только в спецбоксы — не смешивайте с обычным пластиком.',
    'Сдайте стекло отдельно: так оно реально идёт на переплавку.',
    'Фото делайте при хорошем свете — заявки проверяют быстрее.',
    'Серия дней растёт, если сдаёте хотя бы раз в сутки.',
    'Обменивайте баллы на награды кампуса — не копите бесконечно.',
    'Сообщайте о переполненных контейнерах на карте — это помогает операторам.',
  ];

  static String forDay([DateTime? now]) {
    final day = (now ?? DateTime.now()).difference(DateTime(2024)).inDays;
    return items[day % items.length];
  }
}